"""ساخت فایل مشخصات نسخه‌ی exe برای PyInstaller (--version-file): نام محصول، نسخه، توضیح، سازنده و کپی‌رایت در
Properties → Details ویندوز. فایل بدون این مشخصات برای آنتی‌ویروس‌ها مشکوک‌تر است.  python dev/version_info.py build/version_info.txt"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(ROOT, "autokrp", "__init__.py"), encoding="utf-8").read()
ver = re.search(r'__version__\s*=\s*"(\d+)\.(\d+)\.(\d+)"', src).groups()
author = re.search(r'AUTHOR\s*=\s*"([^"]+)"', src).group(1)
v4 = tuple(int(x) for x in ver) + (0,)
vs = ".".join(ver)
TEXT = f"""# UTF-8 — generated by dev/version_info.py
VSVersionInfo(
  ffi=FixedFileInfo(filevers={v4}, prodvers={v4}, mask=0x3f, flags=0x0, OS=0x40004, fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([StringTable('040904B0', [
      StringStruct('CompanyName', '{author}'),
      StringStruct('FileDescription', 'AutoKRP - security and network automation'),
      StringStruct('FileVersion', '{vs}'),
      StringStruct('InternalName', 'AutoKRP'),
      StringStruct('LegalCopyright', 'Copyright (c) 2026 {author}. MIT License.'),
      StringStruct('OriginalFilename', 'AutoKRP.exe'),
      StringStruct('ProductName', 'AutoKRP'),
      StringStruct('ProductVersion', '{vs}'),
      StringStruct('Comments', 'Open source: https://github.com/kamyar-rp/AutoKRP')])]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "build", "version_info.txt")
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, "w", encoding="utf-8").write(TEXT)
print("version info:", out, vs)
