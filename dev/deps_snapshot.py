#!/usr/bin/env python3
"""
فهرست کتابخانه‌هایی که داخل exe می‌روند (requirements.txt + وابستگی‌ها، بدون ابزارهای بیلد) با نسخه‌ی دقیق
← autokrp/build_deps.txt. build.bat پیش از PyInstaller اجرا می‌کند؛ «درباره ← بررسی امنیت» همین فهرست را
با پایگاه OSV مقایسه می‌کند. اجرا: python dev/deps_snapshot.py
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from autokrp.updates import snapshot  # noqa: E402

deps = snapshot(ROOT / "requirements.txt")
out = ROOT / "autokrp" / "build_deps.txt"
out.write_text("# AutoKRP build dependencies (generated by dev/deps_snapshot.py)\n"
               + "".join(f"{k}=={v}\n" for k, v in deps.items()), encoding="utf-8")
print(f"{len(deps)} packages -> {out}")
