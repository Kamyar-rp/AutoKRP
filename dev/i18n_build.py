#!/usr/bin/env python3
"""
ساخت ui/i18n_en.js از ترجمه‌های dev/tr/*.py (به ترتیب dev/i18n_order.json).
متن‌های تازه‌ای که ابزار استخراج پیدا کرده ولی ترجمه ندارند گزارش می‌شوند.
اجرا: python dev/i18n_extract.py && python dev/i18n_build.py
"""
import importlib.util
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
order = json.loads((ROOT / "dev" / "i18n_order.json").read_text(encoding="utf-8"))
T = {}
for f in sorted((ROOT / "dev" / "tr").glob("b*.py")):
    spec = importlib.util.spec_from_file_location(f.stem, f)
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    T.update(m.T)
extra = {}
for ef in sorted((ROOT / "dev" / "tr").glob("extra*.json")):     # extra.json، سپس extra_<نسخه>.json
    extra.update(json.loads(ef.read_text(encoding="utf-8")))
d = {order[i]: en for i, en in T.items() if i < len(order)}
d.update(extra)
for fa, en in d.items():
    if sorted(re.findall(r"\{\d+\}", fa)) != sorted(re.findall(r"\{\d+\}", en)):
        raise SystemExit(f"placeholder mismatch: {fa!r} -> {en!r}")
cur = json.loads((ROOT / "dev" / "i18n_strings.json").read_text(encoding="utf-8"))
missing = [x["fa"] for x in cur if x["fa"] not in d]
out = ROOT / "ui" / "i18n_en.js"
out.write_text("/* AutoKRP English dictionary — generated by dev/i18n_build.py; edit dev/tr/*.py */\n"
               "window.I18N_EN = " + json.dumps(d, ensure_ascii=False, indent=0) + ";\n", encoding="utf-8")
print(f"{len(d)} entries → {out}")
if missing:
    print(f"{len(missing)} untranslated:")
    for m_ in missing:
        print("  ", m_)
